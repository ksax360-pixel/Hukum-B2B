export function dashT(locale: string, text: string) {
  if (!isArLocale(locale)) return text;
  return PHRASE_AR[text] || text;
}

export function dashNavLabel(locale: string, href: string, fallback: string) {
  if (!isArLocale(locale)) return fallback;
  return NAV_AR[href] || PHRASE_AR[fallback] || fallback;
}

export function dashRoleTitle(locale: string, title: string) {
  return dashT(locale, title);
}
