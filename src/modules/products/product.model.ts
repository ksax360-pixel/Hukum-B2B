import { Schema, models, model } from "mongoose";
import {
  LocalizedStringSchema,
  LocalizedStringArraySchema,
  SeoSchema,
  AiFieldMetaSchema,
  DimensionsSchema,
  PriceTierSchema,
  CertificationRecordSchema,
  OriginSchema,
  PackagingSchema,
  LogisticsSchema,
  CustomizationSchema,
  RegionalSchema,
  ProductRelationshipsSchema,
  CURRENCIES,
  PRICE_TYPES,
  PRODUCT_CONDITIONS,
  UNITS,
  MEDIA_TYPES,
  PRODUCT_STATUSES,
} from "@/lib/schemas/common";

const MediaSchema = new Schema(
  {
    url: String,
    type: {
      type: String,
      enum: MEDIA_TYPES,
      default: "image",
    },
    alt: LocalizedStringSchema,
    caption: LocalizedStringSchema,
    order: { type: Number, default: 0 },
    isPrimary: { type: Boolean, default: false },
  },
  { _id: false }
);

const ProductSchema = new Schema(
  {
    vendorId: { type: Schema.Types.ObjectId, ref: "Vendor", required: true, index: true },
    sku: { type: String, index: true },
    productCode: String,
    modelNumber: String,
    name: LocalizedStringSchema,
    title: LocalizedStringSchema,
    shortDescription: LocalizedStringSchema,
    description: LocalizedStringSchema,
    brand: String,
    manufacturer: String,
    manufacturerName: String,
    brandOwner: String,
    distributor: String,
    industryId: { type: Schema.Types.ObjectId, ref: "Industry", index: true },
    industries: [{ type: Schema.Types.ObjectId, ref: "Industry" }],
    categoryId: { type: Schema.Types.ObjectId, ref: "Category", index: true },
    productTypeId: { type: Schema.Types.ObjectId, ref: "Category", index: true },
    categoryPath: [{ type: Schema.Types.ObjectId, ref: "Category" }],
    tags: [String],
    searchTags: [String],
    buyerIntentTags: [String],
    applicationTags: [String],
    synonyms: LocalizedStringArraySchema,
    keywords: LocalizedStringSchema,
    applications: LocalizedStringSchema,
    price: Number,
    currency: { type: String, enum: CURRENCIES, default: "SAR" },
    priceType: { type: String, enum: PRICE_TYPES, default: "price_on_request" },
    priceTiers: [PriceTierSchema],
    samplePrice: Number,
    sampleAvailable: { type: Boolean, default: false },
    minOrderValue: Number,
    tradeTerms: String,
    incoterms: String,
    moq: Number,
    maxOrderQty: Number,
    wholesalePrice: Number,
    retailPrice: Number,
    negotiable: { type: Boolean, default: true },
    requestQuote: { type: Boolean, default: true },
    availability: { type: String, enum: ["in_stock", "out_of_stock", "made_to_order", "limited"], default: "in_stock" },
    leadTime: String,
    deliveryTime: String,
    paymentTerms: String,
    unit: { type: String, enum: UNITS, default: "piece" },
    condition: { type: String, enum: PRODUCT_CONDITIONS, default: "new" },
    dimensions: DimensionsSchema,
    attributes: { type: Map, of: Schema.Types.Mixed },
    /** Seller-added freeform specification rows (key → value), IndiaMART-style */
    customSpecifications: [
      {
        key: { type: String, trim: true },
        value: { type: String, trim: true },
      },
    ],
    /** Embedded variants (color / size / SKU) — also mirrored to ProductVariant on publish later */
    variants: [
      {
        name: String,
        color: String,
        size: String,
        sku: String,
        price: Number,
        stock: Number,
        image: String,
        status: { type: String, enum: ["active", "inactive"], default: "active" },
      },
    ],
    /** Seller-submitted customer testimonials pending admin review (not live marketplace reviews) */
    customerReviews: [
      {
        customerName: { type: String, required: true },
        rating: { type: Number, min: 1, max: 5, default: 5 },
        comment: String,
        images: [String],
        status: {
          type: String,
          enum: ["pending", "approved", "rejected"],
          default: "pending",
        },
        submittedAt: { type: Date, default: Date.now },
      },
    ],
    media: [MediaSchema],
    documents: [{ type: Schema.Types.ObjectId, ref: "Document" }],
    certifications: [String],
    certificationRecords: [CertificationRecordSchema],
    countryOfOrigin: String,
    hsCode: String,
    origin: OriginSchema,
    packaging: PackagingSchema,
    logistics: LogisticsSchema,
    customization: CustomizationSchema,
    regional: RegionalSchema,
    relationships: ProductRelationshipsSchema,
    relatedProducts: [{ type: Schema.Types.ObjectId, ref: "Product" }],
    alternativeProducts: [{ type: Schema.Types.ObjectId, ref: "Product" }],
    accessories: [{ type: Schema.Types.ObjectId, ref: "Product" }],
    spareParts: [{ type: Schema.Types.ObjectId, ref: "Product" }],
    shipping: {
      available: { type: Boolean, default: true },
      deliveryAreas: [String],
      method: String,
      estimatedDelivery: String,
      pickupAvailable: Boolean,
      warehouseLocation: String,
      terms: String,
    },
    status: {
      type: String,
      enum: PRODUCT_STATUSES,
      default: "draft",
      index: true,
    },
    verificationStatus: {
      type: String,
      enum: ["unverified", "pending", "verified", "rejected"],
      default: "unverified",
    },
    completenessScore: { type: Number, default: 0 },
    seoReadinessScore: { type: Number, default: 0 },
    aeoScore: { type: Number, default: 0 },
    seoScoreAr: { type: Number, default: 0 },
    seoScoreEn: { type: Number, default: 0 },
    aeoScoreAr: { type: Number, default: 0 },
    aeoScoreEn: { type: Number, default: 0 },
    geoScore: { type: Number, default: 0 },
    geoScoreAr: { type: Number, default: 0 },
    geoScoreEn: { type: Number, default: 0 },
    discoveryScore: { type: Number, default: 0 },
    productEntityId: { type: Schema.Types.ObjectId, ref: "ProductEntity", index: true },
    marketplaceEntityIds: [{ type: Schema.Types.ObjectId, ref: "MarketplaceEntity", index: true }],
    aeo: Schema.Types.Mixed,
    geo: Schema.Types.Mixed,
    freshnessStatus: {
      type: String,
      enum: ["fresh", "needs_verification", "stale", "expired", "unavailable"],
      default: "fresh",
    },
    seoGaps: [String],
    seo: SeoSchema,
    slug: LocalizedStringSchema,
    aiMeta: { type: Map, of: AiFieldMetaSchema },
    featured: { type: Boolean, default: false },
    paidPriority: { type: Boolean, default: false },
    licenseNumber: { type: String, default: "" },
    compliance: {
      licenseNumber: { type: String, default: "" },
      licenseAuthority: { type: String, default: "" },
      licenseExpiresAt: Date,
    },
    complianceFlags: [{ type: String }],
    moderationStatus: {
      type: String,
      enum: ["none", "needs_review", "cleared", "blocked"],
      default: "none",
      index: true,
    },
    /** Admin moderation note when status → rejected */
    rejectionReason: { type: String, default: "" },
    version: { type: Number, default: 1 },
  },
  { timestamps: true }
);

ProductSchema.index({
  "name.en": "text",
  "name.ar": "text",
  "description.en": "text",
  "description.ar": "text",
  sku: "text",
  brand: "text",
});

export const Product = models.Product || model("Product", ProductSchema);

const ProductVariantSchema = new Schema(
  {
    productId: { type: Schema.Types.ObjectId, ref: "Product", required: true, index: true },
    sku: String,
    name: LocalizedStringSchema,
    attributes: { type: Map, of: Schema.Types.Mixed },
    price: Number,
    currency: { type: String, enum: CURRENCIES, default: "SAR" },
    stock: Number,
    media: [MediaSchema],
    status: { type: String, enum: ["active", "inactive"], default: "active" },
  },
  { timestamps: true }
);

export const ProductVariant = models.ProductVariant || model("ProductVariant", ProductVariantSchema);
